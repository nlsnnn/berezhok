export function getPartnerOfferStorageKey(partnerId) {
  return `${PARTNER_OFFER_STORAGE_PREFIX}:${partnerId || 'unknown'}`
}

export function readAcceptedPartnerOfferVersion(partnerId) {
  if (!partnerId) return null

  try {
    return localStorage.getItem(getPartnerOfferStorageKey(partnerId))
  } catch {
    return null
  }
}

export function writeAcceptedPartnerOfferVersion(partnerId, version = PARTNER_OFFER_VERSION) {
  if (!partnerId) return

  try {
    localStorage.setItem(getPartnerOfferStorageKey(partnerId), version)
  } catch {
    // Ignore storage errors so the UI does not break in restricted environments.
  }
}

export function hasAcceptedCurrentPartnerOffer(partnerId) {
  return readAcceptedPartnerOfferVersion(partnerId) === PARTNER_OFFER_VERSION
}
